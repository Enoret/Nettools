/* =========================================
   NetTools - Internationalization
   The source language of the UI is Spanish. When the language is English the
   Spanish texts are translated on the fly with the I18N_EN dictionary
   (js/i18n-en.js): static HTML, text rendered by the scripts (observed with a
   MutationObserver), toasts and server messages.

   Language: setting 'language' (auto | es | en). 'auto' = browser language:
   Spanish if the browser is in Spanish, English otherwise.

   Dictionary keys may contain placeholders: '{0}', '{1}'... are copied as is,
   '{e}' is translated again (used for error messages from the server).
   Elements marked translate="no" (user data: names, descriptions...) are
   never translated.
   ========================================= */

const I18N = {
    lang: 'es',
    locale: 'es-ES',
    setting: 'auto',
    browserLang: 'es',
    dict: {},
    patterns: [],
    _done: new WeakMap(),
    STORAGE_KEY: 'nettools-language',

    init() {
        try {
            this.setting = localStorage.getItem(this.STORAGE_KEY) || 'auto';
        } catch (e) {
            this.setting = 'auto';
        }
        const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
        this.browserLang = /^es(-|$)/i.test(nav) ? 'es' : 'en';
        this.lang = (this.setting === 'es' || this.setting === 'en') ? this.setting : this.browserLang;
        this.locale = this.lang === 'es' ? 'es-ES' : 'en-GB';
        document.documentElement.lang = this.lang;
        if (this.lang === 'en') {
            this.dict = (typeof I18N_EN !== 'undefined') ? I18N_EN : {};
            this.compile();
            document.title = this.lookup(document.title) || document.title;
            this.translateTree(document.body);
            this.observe();
        }
    },

    /** Called once the server settings are known (see App start-up). */
    syncWithServer(settings) {
        const server = settings.language || 'auto';
        let cached = 'auto';
        try { cached = localStorage.getItem(this.STORAGE_KEY) || 'auto'; } catch (e) { /* ignore */ }
        if (server !== cached) {
            try { localStorage.setItem(this.STORAGE_KEY, server); } catch (e) { /* ignore */ }
            const newLang = (server === 'es' || server === 'en') ? server : this.browserLang;
            if (newLang !== this.lang) {
                window.location.reload();
                return;
            }
        }
        // Telegram messages and device hints are generated by the server:
        // tell it which language the UI uses.
        if (server === 'auto' && settings.ui_language !== this.lang) {
            API.settings.update({ ui_language: this.lang }).catch(() => {});
        }
    },

    compile() {
        const esc = (s) => s.replace(/[.*+?^$()|[\]\\]/g, '\\$&');
        this.patterns = Object.keys(this.dict)
            .filter(k => /\{\w+\}/.test(k))
            .sort((a, b) => b.length - a.length)
            .map(k => {
                const names = [];
                const re = new RegExp('^' + esc(k).replace(/\\?\{(\w+)\\?\}/g, (m, n) => {
                    names.push(n);
                    return '([\\s\\S]*?)';
                }) + '$');
                return { re, names, value: this.dict[k] };
            });
    },

    /** Translation of a whole (trimmed) text, or null. */
    lookup(text, depth = 0) {
        if (!text) return null;
        if (Object.prototype.hasOwnProperty.call(this.dict, text)) return this.dict[text];
        for (const p of this.patterns) {
            const m = p.re.exec(text);
            if (!m) continue;
            let out = p.value;
            p.names.forEach((name, i) => {
                let val = m[i + 1];
                if (name === 'e' && depth < 3) val = this.lookup(val, depth + 1) ?? val;
                out = out.split(`{${name}}`).join(val);
            });
            return out;
        }
        return null;
    },

    /**
     * Translate a Spanish source string. Placeholders {name} are replaced by
     * params[name] after translating.
     */
    t(str, params) {
        let s = this.lang === 'en' ? (this.lookup(str) ?? str) : str;
        if (params) {
            Object.keys(params).forEach(k => { s = s.split(`{${k}}`).join(params[k]); });
        }
        return s;
    },

    // ---------- DOM translation ----------
    ATTRS: ['title', 'placeholder', 'aria-label', 'alt', 'data-tooltip'],

    _skip(el) {
        return !el || !!el.closest('[translate="no"], script, style, textarea, code, pre');
    },

    translateTextNode(node) {
        const raw = node.nodeValue;
        if (!raw || this._done.get(node) === raw) return;
        const trimmed = raw.trim();
        if (!trimmed || !/[A-Za-zÀ-ÿ]/.test(trimmed)) return;
        if (this._skip(node.parentElement)) return;
        const tr = this.lookup(trimmed);
        if (tr !== null && tr !== trimmed) {
            const out = raw.replace(trimmed, tr);
            this._done.set(node, out);
            node.nodeValue = out;
        } else {
            this._done.set(node, raw);
        }
    },

    translateAttributes(el) {
        for (const a of this.ATTRS) {
            const v = el.getAttribute && el.getAttribute(a);
            if (!v) continue;
            const tr = this.lookup(v.trim());
            if (tr !== null && tr !== v) el.setAttribute(a, tr);
        }
    },

    translateTree(root) {
        if (!root) return;
        if (root.nodeType === Node.TEXT_NODE) {
            this.translateTextNode(root);
            return;
        }
        if (root.nodeType !== Node.ELEMENT_NODE || this._skip(root)) return;
        this.translateAttributes(root);
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
            acceptNode: (n) => {
                if (n.nodeType === Node.ELEMENT_NODE) {
                    const tag = n.tagName;
                    if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'TEXTAREA' || n.getAttribute('translate') === 'no') {
                        return NodeFilter.FILTER_REJECT;
                    }
                }
                return NodeFilter.FILTER_ACCEPT;
            },
        });
        let n;
        while ((n = walker.nextNode())) {
            if (n.nodeType === Node.TEXT_NODE) this.translateTextNode(n);
            else this.translateAttributes(n);
        }
    },

    observe() {
        const obs = new MutationObserver((mutations) => {
            for (const m of mutations) {
                if (m.type === 'childList') {
                    m.addedNodes.forEach(n => this.translateTree(n));
                } else if (m.type === 'characterData') {
                    this.translateTextNode(m.target);
                } else if (m.type === 'attributes') {
                    if (!this._skip(m.target)) this.translateAttributes(m.target);
                }
            }
        });
        obs.observe(document.body, {
            childList: true,
            subtree: true,
            characterData: true,
            attributes: true,
            attributeFilter: this.ATTRS,
        });
    },
};
